/* ============================================================================
 * N 皇后问题 —— 回溯法（Backtracking）
 * ============================================================================
 * 【问题】 在 n×n 棋盘上放 n 个皇后，使任意两个皇后不在同一行、同一列、同一对角线。
 *
 * 【回溯法 = 深度优先搜索 + 剪枝】
 *   - 解空间树：把解表示成向量 x[0..n-1]，x[r] 为第 r 行皇后所在的列，
 *     解空间是排列树（本题天然保证各行不冲突，只需检查列与对角线）；
 *   - 从根出发，逐层扩展，每扩展一个结点先用【约束函数】判断是否可行，
 *     不可行就剪掉整棵子树并回退到上一层（回溯）；到达叶子即得到一个可行解。
 *
 * 【冲突判断】 第 r 行皇后在 x[r] 列，第 i 行（i<r）皇后在 x[i] 列：
 *     同列：   x[i] == x[r]
 *     同对角线：|x[i] - x[r]| == r - i   （行差 = 列差，即斜率为 ±1）
 *
 * 【复杂度】 最坏情况指数级（n! 量级），但剪枝后实际远小于此；n 皇后的解个数没有简单公式。
 *
 * 【考点】
 *   ★ 回溯法的概念：深度优先、剪枝（约束函数 + 限界函数）、解空间树的类型
 *     （子集树 2^n，如 0-1 背包；排列树 n!，如 N 皇后、旅行商）。
 *   ★ 8 皇后共 92 个解（去掉旋转、对称后 12 个基本解）；n=2、3 无解；n=4 有 2 个解。
 *   ★ 与分支限界法对比：回溯法用 DFS，求【所有解】或可行解；
 *     分支限界法用 BFS / 最小耗费优先，求【最优解】。
 *   ★ 其他典型回溯问题：图的 m 着色、哈密顿回路、0-1 背包、子集和、迷宫、数独。
 *   ★ 回溯法的通用框架（看懂并能填空）：
 *         backtrack(t):
 *             if t > n: 记录解
 *             else for each 选择 i:
 *                      x[t] = i
 *                      if 约束函数(t) 且 限界函数(t): backtrack(t+1)
 *
 * 【多种实现】
 *   ① 递归回溯（backtrack）；② 非递归回溯（solve_iter）。
 *   二者搜索的是同一棵解空间树、剪枝规则也相同：递归版靠函数调用栈保存"走到哪一行"，
 *   非递归版用变量 r（当前行）和 x[r]（该行试到哪一列）手动维护，前进 r++，回溯 r--。
 *   两种写法都要会：真题有递归版填空，也有非递归版填空。
 * ============================================================================ */
#include <stdlib.h>
#include "common.h"

#define MAXN 12

static int n, x[MAXN], count;               /* x[r]：第 r 行皇后的列号 */

/* 约束函数：第 r 行放在 x[r] 列是否与前 r 行冲突 */
static int place_ok(int r) {
    for (int i = 0; i < r; i++)
        if (x[i] == x[r] || abs(x[i] - x[r]) == r - i) return 0;  /* 【填空①】约束函数：同列 或 同对角线（列差 = 行差） */
    return 1;
}

static void backtrack(int r) {
    if (r == n) {                            /* 【填空②】递归出口：n 行全放好，得到一个解｜前 n 行都放好了：得到一个解 */
        if (count == 0) {                    /* 只打印第一个解 */
            for (int i = 0; i < n; i++) {
                for (int j = 0; j < n; j++) putchar(x[i] == j ? 'Q' : '.');
                putchar('\n');
            }
        }
        count++;
        return;
    }
    for (int c = 0; c < n; c++) {            /* 依次尝试第 r 行的每一列 */
        x[r] = c;
        if (place_ok(r)) backtrack(r + 1);   /* 【填空③】可行才深入下一行，否则剪枝回溯｜可行才深入；不可行即剪枝，循环自动"回溯" */
    }
}

/* ---------------------------------------------------------------------------
 * 非递归回溯：r 为当前行，x[r] 为第 r 行当前试放的列（初值 -1，表示还没试）。
 *   · 找到本行可放的列：若是最后一行 => 得到一个解；否则前进到下一行；
 *   · 本行所有列都试完：回溯到上一行，让上一行换下一列。
 * 返回解的个数。
 * --------------------------------------------------------------------------- */
static int solve_iter(void) {
    int cnt = 0, r = 0;
    x[0] = -1;
    while (r >= 0) {                         /* 【填空④】r<0 说明第 0 行也试完了：搜索结束 */
        x[r]++;                              /* 本行换下一列 */
        while (x[r] < n && !place_ok(r)) x[r]++;   /* 【填空⑤】跳过冲突的列，找第一个可放的 */
        if (x[r] < n) {                      /* 本行有可放的列 */
            if (r == n - 1) cnt++;           /* 最后一行放好 => 一个解；留在本行继续找下一列 */
            else x[++r] = -1;                /* 【填空⑥】前进到下一行，并把下一行的列重置为 -1 */
        } else {
            r--;                             /* 【填空⑦】本行无处可放：回溯到上一行 */
        }
    }
    return cnt;
}

int main(void) {
    /* 下标即 n：n=1 一个解，n=2、3 无解，n=4 两个解 ... n=8 共 92 个 */
    int expect[] = {0, 1, 0, 0, 2, 10, 4, 40, 92};
    for (n = 4; n <= 8; n++) {
        count = 0;
        backtrack(0);
        printf("n=%d solutions=%d\n", n, count);
        CHECK(count == expect[n]);
    }
    for (n = 2; n <= 3; n++) {               /* 无解的情形 */
        count = 0;
        backtrack(0);
        CHECK(count == 0);
    }
    /* 非递归版：解的个数必须与递归版一致 */
    for (n = 4; n <= 8; n++) {
        int c = solve_iter();
        printf("iter n=%d solutions=%d\n", n, c);
        CHECK(c == expect[n]);
    }
    return 0;
}
