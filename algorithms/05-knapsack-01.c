/* ============================================================================
 * 0-1 背包问题 —— 动态规划（Dynamic Programming）
 * ============================================================================
 * 【问题】 n 个物品，重量 w[i]、价值 v[i]，背包容量 C。每个物品要么整个装入(1)
 *          要么不装(0)，不可拆分。求不超过容量的最大总价值。
 *
 * 【动态规划两大特征 —— 必背】
 *   1. 最优子结构：问题的最优解包含子问题的最优解；
 *   2. 重叠子问题：子问题会被反复求解，所以用表格保存（避免重复计算）。
 *
 * 【递推式】 dp[i][c] = 只考虑前 i 个物品、背包容量为 c 时的最大价值
 *     dp[i][c] = dp[i-1][c]                              , c < w[i]（装不下）
 *              = max( dp[i-1][c],                          不装第 i 个
 *                     dp[i-1][c-w[i]] + v[i] )           , c >= w[i]（装第 i 个）
 *     边界：dp[0][*] = 0，dp[*][0] = 0
 *
 * 【复杂度】 时间 O(n*C)，空间 O(n*C)；用一维数组可优化空间到 O(C)（见下）。
 *   ★ 注意：O(n*C) 是"伪多项式"，C 的数值很大时不是真正的多项式时间。
 *
 * 【考点】
 *   ★ 写出递推式、填表（真题常给出 3~4 个物品让你填 dp 表）、回溯出选了哪些物品。
 *   ★ 与"部分背包"对比：部分背包（物品可拆）用贪心；0-1 背包贪心不能得最优，
 *     必须用动态规划（参见 06-fractional-knapsack.c 里的反例）。
 *   ★ 自底向上填表 vs 自顶向下备忘录：二者时间相同。
 *   ★ 一维优化：容量 c 必须从大到小逆序遍历，否则同一物品会被重复装入
 *     （变成完全背包）——高频易错点。
 *
 * 【多种实现】
 *   ① 自底向上二维填表（main 中）；② 一维滚动数组（knapsack_1d）；
 *   ③ 自顶向下备忘录递归（knap_memo）：递归式相同，只计算用到的子问题；
 *   ④ 回溯法（knap_bt）：解空间是子集树，用约束函数 + 上界函数剪枝。
 *   不带备忘录的纯递归是指数级 O(2^n)，备忘录后降为 O(n*C)。
 * ============================================================================ */
#include "common.h"

#define N 3
#define C 50

/* 一维滚动数组版：f[c] 表示容量 c 时的最大价值。
 * 逆序遍历 c 保证 f[c-w[i]] 还是"上一轮(i-1)"的值。 */
static int knapsack_1d(const int w[], const int v[], int n, int cap) {
    int f[C + 1] = {0};
    for (int i = 1; i <= n; i++)
        for (int c = cap; c >= w[i]; c--)    /* 【填空①】一维优化：容量必须逆序，否则同一物品重复装入｜必须逆序！ */
            if (f[c - w[i]] + v[i] > f[c]) f[c] = f[c - w[i]] + v[i];
    return f[cap];
}

/* ---------------------------------------------------------------------------
 * 实现③：备忘录（Memoization）递归 —— 自顶向下的动态规划
 * kmemo[i][c] = -1 表示该子问题还没算过；算过就直接返回，避免重复计算。
 * --------------------------------------------------------------------------- */
static int kmemo[N + 1][C + 1];

static int knap_memo(const int w[], const int v[], int i, int c) {
    if (i == 0) return 0;                    /* 【填空②】没有物品可选 */
    if (kmemo[i][c] >= 0) return kmemo[i][c];   /* 【填空③】已算过：直接查表 */
    int best = knap_memo(w, v, i - 1, c);    /* 不装第 i 个 */
    if (c >= w[i]) {
        int t = knap_memo(w, v, i - 1, c - w[i]) + v[i];  /* 装第 i 个 */
        if (t > best) best = t;
    }
    return kmemo[i][c] = best;               /* 【填空④】先存表再返回 */
}

/* ---------------------------------------------------------------------------
 * 实现④：回溯法 —— 解空间树是【子集树】，每个物品有"装 / 不装"两个分支。
 *   约束函数：装入后重量不超过容量，否则不进左子树；
 *   上界函数：当前价值 + 剩余物品全部价值 <= 已知最优，则剪掉该子树。
 * --------------------------------------------------------------------------- */
static int bt_best;

static void knap_bt(const int w[], const int v[], int i, int cw, int cv) {
    if (i > N) {                             /* 到达叶子：一个完整方案 */
        if (cv > bt_best) bt_best = cv;
        return;
    }
    int rest = 0;
    for (int k = i; k <= N; k++) rest += v[k];
    if (cv + rest <= bt_best) return;        /* 【填空⑤】上界函数剪枝 */
    if (cw + w[i] <= C)                      /* 【填空⑥】约束函数：装得下才走左子树 */
        knap_bt(w, v, i + 1, cw + w[i], cv + v[i]);
    knap_bt(w, v, i + 1, cw, cv);            /* 右子树：不装第 i 个 */
}

int main(void) {
    int w[N + 1] = {0, 10, 20, 30};          /* 下标从 1 开始，w[0] 占位 */
    int v[N + 1] = {0, 60, 100, 120};
    static int dp[N + 1][C + 1];             /* static：自动初始化为 0，即边界条件 */

    /* 填表：按物品从前往后、容量从小到大 */
    for (int i = 1; i <= N; i++)
        for (int c = 0; c <= C; c++) {
            dp[i][c] = dp[i - 1][c];         /* 【填空⑦】不装第 i 个物品（或装不下）：继承上一行｜先假设不装第 i 个 */
            if (c >= w[i] && dp[i - 1][c - w[i]] + v[i] > dp[i][c])  /* 【填空⑧】装得下且装了更优：递推式的核心 */
                dp[i][c] = dp[i - 1][c - w[i]] + v[i]; /* 装第 i 个更优 */
        }

    printf("max value = %d\nchosen items:", dp[N][C]);

    /* 回溯构造解：若 dp[i][c] != dp[i-1][c]，说明第 i 个物品被选中 */
    int c = C, total = 0;
    for (int i = N; i >= 1; i--)
        if (dp[i][c] != dp[i - 1][c]) {  /* 【填空⑨】回溯：与上一行不同说明第 i 个物品被选中 */
            printf(" %d", i);
            c -= w[i];                       /* 【填空⑩】回溯时扣除已选物品的重量｜扣除已选物品的重量 */
            total += v[i];
        }
    printf("\n");

    CHECK(dp[N][C] == 220);                  /* 选物品 2(20,100) + 3(30,120) */
    CHECK(total == 220);
    CHECK(knapsack_1d(w, v, N, C) == 220);   /* 一维优化结果应一致 */
    /* 备忘录递归 */
    for (int i = 0; i <= N; i++)
        for (int k = 0; k <= C; k++) kmemo[i][k] = -1;
    CHECK(knap_memo(w, v, N, C) == 220);

    /* 回溯法 */
    bt_best = 0;
    knap_bt(w, v, 1, 0, 0);
    CHECK(bt_best == 220);
    return 0;
}
