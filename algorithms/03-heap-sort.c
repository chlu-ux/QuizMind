/* ============================================================================
 * 堆排序（Heap Sort）—— 选择类排序
 * ============================================================================
 * 【堆的定义】
 *   完全二叉树，且任一结点 >= 其左右孩子（大顶堆）或 <= 其左右孩子（小顶堆）。
 *   用数组顺序存储：
 *     - 下标从 0 开始：i 的左孩子 2i+1，右孩子 2i+2，父亲 (i-1)/2
 *     - 下标从 1 开始：i 的左孩子 2i  ，右孩子 2i+1，父亲 i/2   （教材/真题常用）
 *
 * 【算法思想】
 *   1. 建堆：把无序数组调整为大顶堆，从最后一个非叶子结点开始向前逐个"下沉"；
 *   2. 排序：堆顶（最大值）与堆尾交换，堆长度减 1，再对堆顶下沉；重复。
 *   升序用大顶堆，降序用小顶堆。
 *
 * 【复杂度】
 *   - 建堆 O(n)（不是 O(n log n)！这是常见易错点）
 *   - 排序 n-1 次下沉，每次 O(log n) => 总体 O(n log n)，最好最坏平均都一样
 *   - 空间 O(1)，原地排序；不稳定
 *
 * 【考点】
 *   ★ 最后一个非叶子结点：0-based 为 n/2-1；1-based 为 ⌊n/2⌋。
 *   ★ 给定序列判断是否为堆 / 手工建堆后的序列 / 删除堆顶后重新调整的结果。
 *   ★ 对比：堆排序最坏仍 O(n log n) 且空间 O(1)，但不稳定、常数比快排大；
 *     适合求 Top-K（只需要前 k 大/小，不必全部排序）。
 *   ★ 堆也是优先队列的实现基础；Dijkstra / Prim 的堆优化用到小顶堆。
 *   ★ 堆排序不适合链式存储（需要随机访问下标计算孩子）。
 * ============================================================================ */
#include "common.h"

/* 向下调整（下沉）：以 i 为根、堆长度为 n 的子树，左右子树已是堆，
 * 只有根可能破坏堆性质。把根沿着较大的孩子一路下移到合适位置。 */
static void sift_down(int a[], int i, int n) {
    int x = a[i];                            /* 暂存根，空出一个"坑" */
    for (int child = 2 * i + 1; child < n; child = 2 * i + 1) {  /* 【填空①】左孩子下标 2i+1（1-based 为 2i） */
        if (child + 1 < n && a[child + 1] > a[child]) child++; /* 【填空②】选左右孩子中较大者（大顶堆）；child+1<n 的越界判断常被挖空｜选较大的孩子 */
        if (a[child] <= x) break;            /* 根不小于孩子：位置合适 */
        a[i] = a[child];                     /* 孩子上移 */
        i = child;                           /* 坑下移 */
    }
    a[i] = x;
}

static void heap_sort(int a[], int n) {
    /* 建堆：从最后一个非叶子结点 n/2-1 倒序到根，逐个下沉 */
    for (int i = n / 2 - 1; i >= 0; i--) sift_down(a, i, n);  /* 【填空③】建堆：从最后一个非叶子 n/2-1 倒序到 0 逐个下沉 */
    /* 排序：每轮把当前最大值换到末尾，堆缩小 1 再调整 */
    for (int end = n - 1; end > 0; end--) {
        int t = a[0]; a[0] = a[end]; a[end] = t;  /* 【填空④】堆顶（最大值）与堆尾交换 */
        sift_down(a, 0, end);                /* 【填空⑤】堆长度缩为 end，对堆顶重新调整｜注意堆长度是 end，已排好的不再参与 */
    }
}

int main(void) {
    int a[] = {49, 38, 65, 97, 76, 13, 27, 49, 55, 4};
    int n = sizeof a / sizeof a[0];
    print_array("before", a, n);

    /* 建堆后的大顶堆（手算可对照）：堆顶应为最大值 97 */
    int h[10];
    for (int i = 0; i < n; i++) h[i] = a[i];
    for (int i = n / 2 - 1; i >= 0; i--) sift_down(h, i, n);
    print_array("heap  ", h, n);
    CHECK(h[0] == 97);
    for (int i = 1; i < n; i++) CHECK(h[(i - 1) / 2] >= h[i]); /* 满足大顶堆性质 */

    heap_sort(a, n);
    print_array("after ", a, n);
    CHECK(is_sorted(a, n));
    return 0;
}
