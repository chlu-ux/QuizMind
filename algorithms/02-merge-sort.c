/* ============================================================================
 * 归并排序（Merge Sort）—— 分治法
 * ============================================================================
 * 【算法思想】
 *   1. 分解：把序列从中间一分为二，直到每段只有 1 个元素（天然有序）；
 *   2. 求解：递归排序两半；
 *   3. 合并：把两个有序子序列合并成一个有序序列（二路归并），这是核心。
 *
 * 【复杂度】
 *   - 时间：任何情况都是 O(n log n)。递归式 T(n)=2T(n/2)+O(n)，
 *           由主定理得 Θ(n log n)；共 ⌈log2 n⌉ 趟，每趟合并 O(n)。
 *   - 空间：O(n)（需要等长的辅助数组），递归栈 O(log n)。
 *   - 稳定性：稳定（合并时左半部分元素相等时先取左边，见下面的 <=）。
 *
 * 【考点】
 *   ★ 稳定 + 最坏仍为 O(n log n)，代价是 O(n) 额外空间——与快排、堆排序比较
 *     时间 / 空间 / 稳定性的"三栏表"是高频选择题。
 *   ★ 二路归并的趟数：n 个元素需要 ⌈log2 n⌉ 趟；k 路归并需要 ⌈logk n⌉ 趟。
 *   ★ 一趟归并后的序列：初始每个元素是长度为 1 的有序段，
 *     第 1 趟得到长度 2 的有序段，第 2 趟得到长度 4 ……（"第几趟后结果"常考）。
 *   ★ 两个长度为 m、n 的有序表合并，比较次数最少 min(m,n)，最多 m+n-1。
 *   ★ 外部排序（大文件排序）的基础就是归并。
 *
 * 【多种实现】
 *   ① 自顶向下递归（merge_sort）：先分后合；
 *   ② 自底向上非递归（merge_sort_iter）：直接从长度 1 的有序段开始，
 *      每趟把相邻两段归并，段长 1,2,4,8... 翻倍，共 ⌈log2 n⌉ 趟。
 *   教材讲"一趟归并"、考"第几趟后的序列"，对应的就是非递归写法。
 * ============================================================================ */
#include "common.h"

/* 合并 a[lo..mid] 与 a[mid+1..hi] 两个有序段 */
static void merge(int a[], int tmp[], int lo, int mid, int hi) {
    int i = lo, j = mid + 1, k = lo;
    /* 取较小者放入 tmp。相等时先取左段(i)，保证稳定性——写成 < 就不稳定了 */
    while (i <= mid && j <= hi) tmp[k++] = (a[i] <= a[j]) ? a[i++] : a[j++];  /* 【填空①】比较两段队首取较小者；用 <= 保证稳定 */
    while (i <= mid) tmp[k++] = a[i++];     /* 【填空②】左段剩余元素直接拷贝；与下一行的右段剩余常成对考｜左段有剩余 */
    while (j <= hi)  tmp[k++] = a[j++];     /* 右段有剩余（两个循环只会执行一个） */
    for (k = lo; k <= hi; k++) a[k] = tmp[k]; /* 拷回原数组 */
}

static void merge_sort(int a[], int tmp[], int lo, int hi) {
    if (lo >= hi) return;                   /* 递归出口：单元素 */
    int mid = lo + (hi - lo) / 2;           /* 【填空③】划分点 mid｜写法避免 lo+hi 溢出 */
    merge_sort(a, tmp, lo, mid);
    merge_sort(a, tmp, mid + 1, hi);
    merge(a, tmp, lo, mid, hi);  /* 【填空④】合并放在两次递归之后（后序） */
}

/* ---------------------------------------------------------------------------
 * 非递归（自底向上）归并排序：w 为当前每个有序段的长度。
 * 每一趟把 [lo, lo+w-1] 与 [lo+w, lo+2w-1] 两段合并，最后一段不足 w 时保持原样。
 * --------------------------------------------------------------------------- */
static int trace;                            /* 为 1 时打印每一趟的结果 */

static void merge_sort_iter(int a[], int tmp[], int n) {
    for (int w = 1; w < n; w *= 2) {         /* 【填空⑤】段长 1,2,4,... 每趟翻倍 */
        for (int lo = 0; lo < n - w; lo += 2 * w) {  /* lo < n-w：保证右段至少有 1 个元素 */
            int mid = lo + w - 1;
            int hi = (lo + 2 * w - 1 < n) ? lo + 2 * w - 1 : n - 1;  /* 【填空⑥】右段可能不足 w，取到 n-1 */
            merge(a, tmp, lo, mid, hi);
        }
        if (trace) { printf("w=%d ", w); print_array("pass", a, n); }
    }
}

int main(void) {
    int a[] = {49, 38, 65, 97, 76, 13, 27, 49, 55, 4};
    int n = sizeof a / sizeof a[0];
    int tmp[sizeof a / sizeof a[0]];        /* 辅助数组：O(n) 空间的来源 */
    print_array("before", a, n);
    merge_sort(a, tmp, 0, n - 1);
    print_array("after ", a, n);
    CHECK(is_sorted(a, n));
    /* 非递归版：打印每一趟的结果，对照"第几趟后序列"类题目 */
    int c[] = {49, 38, 65, 97, 76, 13, 27, 49, 55, 4};
    trace = 1;
    merge_sort_iter(c, tmp, n);
    trace = 0;
    CHECK(is_sorted(c, n));
    return 0;
}
