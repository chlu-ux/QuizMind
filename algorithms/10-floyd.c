/* ============================================================================
 * Floyd（Floyd-Warshall）多源最短路径 —— 动态规划
 * ============================================================================
 * 【问题】 求带权图中【任意两点】之间的最短路径。
 *
 * 【算法思想】 设 d_k[i][j] 表示"只允许经过编号 <= k 的顶点作中转"时 i 到 j 的最短距离：
 *     d_k[i][j] = min( d_{k-1}[i][j],                 不经过 k
 *                      d_{k-1}[i][k] + d_{k-1}[k][j] ) 经过 k
 *   k 从 0 到 n-1，依次把每个顶点"加入"为可中转点。
 *   可以原地在一个二维数组上更新（k 那一行/列在第 k 轮不会变）。
 *
 * 【复杂度】 时间 O(n^3)（三重循环），空间 O(n^2)。
 *
 * 【考点】
 *   ★ 三重循环中【k 必须在最外层】，这是最高频的易错点（也是填空题的挖空点）。
 *     把 k 放内层会得到错误结果。
 *   ★ 允许有负权边，但不能有负权回路。
 *   ★ 单源（Dijkstra，贪心，要求非负权）vs 多源（Floyd，动态规划）。
 *   ★ 邻接矩阵初始化：对角线为 0，无边为 INF；INF 参与加法要防溢出
 *     （用较小的 INF，或加法前判断是否 INF）。
 *   ★ 要输出路径需额外维护 path[i][j] 记录中转点。
 *   ★ 也可用于求传递闭包（Warshall 算法）：把 + 和 min 换成 && 和 ||。
 * ============================================================================ */
#include "common.h"

#define N 4
#define INF 1000000

int main(void) {
    /* 有向图的邻接矩阵：d[i][j] 为 i->j 的边权 */
    int d[N][N] = {
        {0,   5,   INF, 10},
        {INF, 0,   3,   INF},
        {INF, INF, 0,   1},
        {INF, INF, INF, 0},
    };

    /* k：中转点（最外层！）；i：起点；j：终点 */
    for (int k = 0; k < N; k++)  /* 【填空①】k（中转点）必须在最外层 */
        for (int i = 0; i < N; i++)
            for (int j = 0; j < N; j++)
                if (d[i][k] + d[k][j] < d[i][j])  /* 【填空②】经 k 中转是否更短：Floyd 的递推式 */
                    d[i][j] = d[i][k] + d[k][j];

    for (int i = 0; i < N; i++) {
        for (int j = 0; j < N; j++) {
            if (d[i][j] >= INF) printf("%4s", "INF");
            else printf("%4d", d[i][j]);
        }
        printf("\n");
    }

    CHECK(d[0][2] == 8);                     /* 0->1->2 = 5+3 */
    CHECK(d[0][3] == 9);                     /* 0->1->2->3 = 9，优于直连的 10 */
    CHECK(d[1][3] == 4);                     /* 1->2->3 = 3+1 */
    CHECK(d[3][0] >= INF);                   /* 有向图中 3 无法到达 0 */
    return 0;
}
