/* ============================================================================
 * 活动安排问题（Activity Selection）—— 贪心法
 * ============================================================================
 * 【问题】 n 个活动竞争同一场地，活动 i 占用时间 [s_i, f_i)。两个活动相容 = 时间不重叠。
 *          求最多能安排多少个互相相容的活动。
 *
 * 【贪心策略】 按【结束时间】升序排序；先选第一个，之后依次选择开始时间
 *              >= 上一个已选活动结束时间的活动。
 *   直觉：结束得最早，给后面的活动留下的时间最多。
 *
 * 【为什么不是按开始时间或活动时长？】（高频追问）
 *   - 按开始时间最早：一个很长的活动 [0,100) 会挡住后面所有短活动；
 *   - 按持续时间最短：短活动 [4,6) 可能卡在 [1,5) 和 [5,9) 中间，导致这两个都不能选。
 *   只有"结束时间最早"能被证明是最优的（贪心选择性质）。
 *
 * 【复杂度】 排序 O(n log n)；排序后一次扫描 O(n)。
 *
 * 【考点】
 *   ★ 贪心选择性质的证明思路：设最优解的第一个活动是 k，把它换成结束最早的活动 1，
 *     解仍然相容且数量不变，所以存在包含活动 1 的最优解。
 *   ★ 同类题型：会议室安排、区间调度、区间选点 / 区间覆盖等。
 *   ★ 与动态规划对比：这里每步选择后只剩一个子问题，不需要比较多个子问题，所以贪心更简单。
 *   ★ 注意"相容"的边界：s_i >= f_j 才算相容（首尾相接可以），因为用的是半开区间。
 *
 * 【多种实现】
 *   ① 迭代（main 中的 for 循环）；② 递归（rec_select，《算法导论》RECURSIVE-ACTIVITY-SELECTOR）。
 *   递归版以"上一个已选活动 k"为参数，找到第一个与 k 相容的活动 m，选中后对 m 继续递归。
 * ============================================================================ */
#include "common.h"

#define N 11

/* ---------------------------------------------------------------------------
 * 递归版：k 为上一个已选活动的下标（-1 表示还没选），返回已选活动个数。
 * --------------------------------------------------------------------------- */
static int rec_select(const int s[], const int f[], int k, int n, int chosen[], int cnt) {
    int m = k + 1;
    int last_end = (k < 0) ? 0 : f[k];
    while (m < n && s[m] < last_end) m++;    /* 【填空①】跳过与 k 不相容的活动 */
    if (m >= n) return cnt;                  /* 递归出口：没有可选的活动了 */
    chosen[cnt++] = m;
    return rec_select(s, f, m, n, chosen, cnt);   /* 【填空②】以 m 为新的"上一个活动"继续 */
}

int main(void) {
    /* 已按结束时间 f 升序排好（实际题目要先排序，O(n log n)） */
    int s[N] = {1, 3, 0, 5, 3, 5, 6, 8, 8, 2, 12};
    int f[N] = {4, 5, 6, 7, 9, 9, 10, 11, 12, 14, 16};

    int chosen[N], cnt = 0, last_end = 0;    /* last_end：已选活动的最晚结束时间 */
    for (int i = 0; i < N; i++)
        if (s[i] >= last_end) {              /* 【填空③】相容判断：开始时间 >= 上一个已选活动的结束时间｜与已选活动相容：选！ */
            chosen[cnt++] = i;
            last_end = f[i];  /* 【填空④】更新最后结束时间 */
        }

    printf("selected %d activities:", cnt);
    for (int i = 0; i < cnt; i++) printf(" [%d,%d)", s[chosen[i]], f[chosen[i]]);
    printf("\n");

    CHECK(cnt == 4);                         /* 最多 4 个：[1,4) [5,7) [8,11) [12,16) */
    for (int i = 1; i < cnt; i++)            /* 验证确实两两相容 */
        CHECK(s[chosen[i]] >= f[chosen[i - 1]]);
    /* 递归版：选出的活动应与迭代版完全相同 */
    int chosen2[N];
    int cnt2 = rec_select(s, f, -1, N, chosen2, 0);
    CHECK(cnt2 == cnt);
    for (int i = 0; i < cnt; i++) CHECK(chosen2[i] == chosen[i]);
    return 0;
}
