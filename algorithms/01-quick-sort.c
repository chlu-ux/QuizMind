/* ============================================================================
 * 快速排序（Quick Sort）—— 分治法
 * ============================================================================
 * 【算法思想】
 *   1. 分解：选一个枢轴（pivot），一趟划分后，枢轴左边的元素都 <= 枢轴，
 *            右边的元素都 >= 枢轴，枢轴落在它最终的有序位置上；
 *   2. 求解：对左、右两个子区间分别递归排序；
 *   3. 合并：无需合并（原地排序，这是与归并排序的区别）。
 *
 * 【复杂度】
 *   - 最好 / 平均：O(n log n)    （每次划分都比较均匀）
 *   - 最坏      ：O(n^2)        （序列已有序或逆序，且枢轴取首/尾元素时，
 *                                 每次只划出 1 个元素：T(n)=T(n-1)+O(n)）
 *   - 空间      ：平均 O(log n)，最坏 O(n)（递归栈深度）
 *   - 稳定性    ：不稳定（划分时元素会跨越相同值的元素）
 *
 * 【考点】
 *   ★ 一趟划分的结果：真题最爱问"第一趟排序后的序列是什么"，必须会手算
 *     （下面 main 里给出了本例第一趟结果，并用 CHECK 验证）。
 *   ★ 最坏情况出现在"基本有序"的序列上，此时快排反而最慢；
 *     而此时直接插入排序、冒泡（带标志）接近 O(n)。
 *   ★ 平均性能最好的内部排序（基于比较），但不稳定。
 *   ★ 分治法的典型代表之一，递归式 T(n)=T(k)+T(n-k-1)+O(n)。
 *   ★ 常见优化：三数取中 / 随机选枢轴避免最坏；小区间改用插入排序；
 *     先递归较短的一侧以把栈深度控制在 O(log n)。
 *   ★ 与堆排序、归并排序对比：三者平均都是 O(n log n)；
 *     只有归并排序稳定；只有堆排序最坏也是 O(n log n) 且空间 O(1)。
 *
 * 【多种实现】
 *   ① 递归（quick_sort）；② 非递归：显式栈保存待排区间（quick_sort_iter）。
 *   考点：递归与栈的相互转换。先处理较短的一侧、把较长的一侧留在栈里，
 *   栈深度可保证为 O(log n)；否则最坏（有序序列）栈深度 O(n)。
 *   划分函数也有多种写法：挖坑填数（本文件）、Hoare 双指针交换、Lomuto 单向扫描。
 * ============================================================================ */
#include "common.h"

/* 一趟划分（"挖坑填数"写法，教材/真题最常见）。
 * 把 a[lo] 取出作为枢轴，形成一个"坑"；
 * 然后 hi 从右往左找第一个 < 枢轴 的数填到左坑，
 *      lo 从左往右找第一个 > 枢轴 的数填到右坑，
 * 直到 lo == hi，把枢轴填入最后的坑，返回它的位置。 */
static int partition(int a[], int lo, int hi) {
    int pivot = a[lo];                       /* 枢轴取区间首元素 */
    while (lo < hi) {
        while (lo < hi && a[hi] >= pivot) hi--; /* 【填空①】从右向左找第一个 < 枢轴的数；比较符号、lo<hi 条件常被挖空｜易错：必须带 lo<hi，否则越界 */
        a[lo] = a[hi];                          /* 【填空②】右侧小数填入左坑；赋值方向常被挖空｜右侧小数填左坑 */
        while (lo < hi && a[lo] <= pivot) lo++;
        a[hi] = a[lo];                          /* 左侧大数填右坑 */
    }
    a[lo] = pivot;                           /* 【填空③】枢轴填入最后的坑，返回其下标｜枢轴就位：此后它的位置不再改变 */
    return lo;
}

static void quick_sort(int a[], int lo, int hi) {
    if (lo >= hi) return;                    /* 【填空④】递归出口：区间内元素 <=1 个（lo>=hi）｜递归出口：区间内 0 或 1 个元素 */
    int p = partition(a, lo, hi);
    quick_sort(a, lo, p - 1);                /* 【填空⑤】递归两个子区间 [lo,p-1] 与 [p+1,hi]，枢轴不再参与｜枢轴本身不再参与 */
    quick_sort(a, p + 1, hi);
}

/* ---------------------------------------------------------------------------
 * 非递归快速排序：用数组模拟栈，栈中成对存放待排序区间的 lo、hi。
 * 递归版的"递归调用"在这里变成"把子区间压栈"，"函数返回"变成"弹栈取下一个区间"。
 * --------------------------------------------------------------------------- */
static void quick_sort_iter(int a[], int n) {
    int stack[128], top = 0;                 /* 先压较长区间 => 栈深度 O(log n)，128 足够 */
    stack[top++] = 0;
    stack[top++] = n - 1;
    while (top > 0) {                        /* 【填空⑥】栈不空就继续：相当于递归版"还有子问题" */
        int hi = stack[--top];               /* 出栈顺序与入栈相反：先 hi 后 lo */
        int lo = stack[--top];
        if (lo >= hi) continue;              /* 与递归出口相同 */
        int p = partition(a, lo, hi);
        if (p - lo > hi - p) {               /* 左区间更长：先压左，右区间下一轮先出栈 */
            stack[top++] = lo;     stack[top++] = p - 1;
            stack[top++] = p + 1;  stack[top++] = hi;
        } else {
            stack[top++] = p + 1;  stack[top++] = hi;
            stack[top++] = lo;     stack[top++] = p - 1;
        }
    }
}

int main(void) {
    int a[] = {49, 38, 65, 97, 76, 13, 27, 49, 55, 4};
    int n = sizeof a / sizeof a[0];
    print_array("before", a, n);

    /* 第一趟划分（枢轴 49）：手算过程
     *   初始  [49 38 65 97 76 13 27 49 55 4]
     *   结果  [ 4 38 27 13 49 76 97 49 55 65]   枢轴 49 落在下标 4
     * 不稳定的来源：划分时元素会跨过一大段区间被"甩"到另一侧，相等元素的相对
     * 顺序可能颠倒（例如序列 [2, 2, 1]，以首个 2 为枢轴划分后两个 2 的次序就变了）。 */
    int b[10];
    for (int i = 0; i < n; i++) b[i] = a[i];
    int p = partition(b, 0, n - 1);
    print_array("pass 1", b, n);
    int expect[] = {4, 38, 27, 13, 49, 76, 97, 49, 55, 65};
    CHECK(p == 4);
    for (int i = 0; i < n; i++) CHECK(b[i] == expect[i]);

    quick_sort(a, 0, n - 1);
    print_array("after ", a, n);
    CHECK(is_sorted(a, n));
    /* 非递归版：结果应与递归版一致 */
    int c[] = {49, 38, 65, 97, 76, 13, 27, 49, 55, 4};
    quick_sort_iter(c, n);
    print_array("iter  ", c, n);
    CHECK(is_sorted(c, n));
    int sorted[300];                         /* 有序输入是递归版的最坏情形，非递归版栈仍不溢出 */
    for (int i = 0; i < 300; i++) sorted[i] = i;
    quick_sort_iter(sorted, 300);
    CHECK(is_sorted(sorted, 300));
    return 0;
}
